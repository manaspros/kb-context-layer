"""`kb eval`: the one command. Default rebuilds every table from the committed raw outputs (no network, no LLM);
`--rerun` first re-executes every LLM system, then does the same."""
import argparse
import contextlib
import hashlib
import io
import json
import os
import sys

from kb import score
from kb.common import RESULTS, ROOT, read_jsonl

SPLITS = {"subset_ids.txt": ("subset_ids.sha256", 400), "tune_ids.txt": ("tune_ids.sha256", 200)}
UNANS_FILE, UNANS_SHA = "unanswerable.jsonl", "unanswerable.sha256"
LLM_SYSTEMS = ["closed", "bm25", "dense", "rrf", "kb", "kb_hop0", "kb_no_lookup", "kb_no_graph", "rrf_unans", "kb_unans"]
EXPECTED_N = {"kb_no_graph": 267, "rrf_unans": 60, "kb_unans": 60}  # every other system answers the 400 subset
REQUIRED_ENV = ("LLM_BASE_URL", "LLM_API_KEY", "LLM_MODEL")
SYSTEM_LABEL = {"closed": "closed-book", "bm25": "BM25", "dense": "dense (bge-small)", "rrf": "RRF (BM25+dense)",
                "kb": "kb (full)", "kb_hop0": "kb, no hops", "kb_no_lookup": "kb, no entity lookup",
                "kb_no_graph": "kb, no graph (n=267)"}


def sha(path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_inputs() -> dict[str, str]:
    """Id files match their committed sha256; splits are disjoint; every answer file covers exactly its question set."""
    d, fp = ROOT / "data", {}
    ids = {}
    for name, (shaf, n) in {**SPLITS, UNANS_FILE: (UNANS_SHA, 60)}.items():
        assert sha(d / name) == (d / shaf).read_text().strip(), f"{name}: sha256 does not match {shaf}"
        ids[name] = set((d / name).read_text().split()) if name.endswith(".txt") else {r["id"] for r in read_jsonl(d / name)}
        assert len(ids[name]) == n, f"{name}: expected {n} ids, found {len(ids[name])}"
        fp[name] = sha(d / name)
    assert not (ids["subset_ids.txt"] & ids["tune_ids.txt"]), "tune split overlaps the eval subset"
    assert not (ids[UNANS_FILE] & (ids["subset_ids.txt"] | ids["tune_ids.txt"])), "probe overlaps eval or tune"
    for s in LLM_SYSTEMS:
        rows = read_jsonl(RESULTS / "answers" / f"{s}.jsonl")
        got, want = {r["id"] for r in rows}, ids[UNANS_FILE] if s.endswith("_unans") else ids["subset_ids.txt"]
        assert len(rows) == EXPECTED_N.get(s, 400) and got <= want, f"results/answers/{s}.jsonl: unexpected question ids"
        fp[f"answers/{s}.jsonl"] = sha(RESULTS / "answers" / f"{s}.jsonl")
    return fp


def pct(x) -> str:
    return "-" if x is None else f"{x:.3f}"


def render(sm: dict, fp: dict[str, str]) -> str:
    S, out = sm["systems"], []

    def table(head: list[str], rows: list[list]) -> None:
        out.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head))
        out.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)
        out.append("")

    out += ["# Results (generated by `python -m kb eval`; do not edit)\n", "## Systems, 400 questions (kb_no_graph: 267)\n"]
    keys = ("em", "f1", "all_gold_docs", "cited2", "em_answered", "answered", "abstain", "empty", "calls", "tokens")
    table(["system", "n", "EM", "F1", "all-gold in context", "cited >=2 gold docs", "EM when answered", "answered",
           "abstain", "empty", "calls/q", "tokens/q"],
          [[SYSTEM_LABEL[s], S[s]["all"]["n"], *[("-" if s == "closed" and k in ("all_gold_docs", "cited2") else pct(S[s]["all"][k])) if k not in ("calls", "tokens") else f"{S[s]['all'][k]:.1f}" for k in keys]]
           for s in S])
    out.append("## EM by hop count\n")
    table(["system", "2-hop", "3-hop", "4-hop"], [[SYSTEM_LABEL[s], *[pct(S[s][h]["em"]) for h in "234"]] for s in S])
    out.append("## Paired bootstrap, kb minus X (10,000 resamples, seed 0, 95% CI, questions paired)\n")
    table(["comparison", "n", "EM", "F1", "all-gold in context", "cited >=2 gold docs"],
          [[f"kb - {k.removeprefix('kb-')}", b["all"]["em"]["n"],
            *[f"{b['all'][m]['delta']:+.3f} [{b['all'][m]['ci95'][0]:+.3f}, {b['all'][m]['ci95'][1]:+.3f}]" for m in ("em", "f1", "all_gold_docs", "cited2")]]
           for k, b in sm["bootstrap"].items()])
    out.append("## Ablation on the same 267 questions\n")
    table(["system", "n", "EM", "F1", "all-gold in context", "cited >=2 gold docs", "tokens/q"],
          [[SYSTEM_LABEL[s], a["n"], pct(a["em"]), pct(a["f1"]), pct(a["all_gold_docs"]), pct(a["cited2"]), f"{a['tokens']:.0f}"]
           for s, a in sm["ablation_subset"].items()])
    out.append("## Failure stage (wrong = EM 0 and F1 < 0.5; correct_citation_gap = correct but no gold document cited)\n")
    table(["system", *score.STAGES], [[SYSTEM_LABEL[s], *[S[s]["all"]["stages"][k] for k in score.STAGES]] for s in S if s != "closed"])
    out.append("## Citation checks per claim\n\nMechanical: span id exists in the context, quote is a substring. "
               "NLI: MiniCheck-RoBERTa-Large, premise = cited span text, claim supported if P >= 0.5 (recall = supported claims / claims; "
               "unsupported = 1 - recall; precision = relevant citations / citations).\n")
    V = sm["verify"]
    table(["system", "claims", "span ids valid", "quote verbatim", "NLI recall", "NLI precision", "NLI unsupported", "context utilization"],
          [[SYSTEM_LABEL[s], S[s]["all"]["claims"], pct(S[s]["all"]["cite_ids_ok"]), pct(S[s]["all"]["cite_quote_ok"]),
            pct(V[s]["citation_recall"]) if s in V else "-", pct(V[s]["citation_precision"]) if s in V else "-",
            pct(V[s]["unsupported_claim_rate"]) if s in V else "-", pct(S[s]["all"]["utilization"])] for s in S if s != "closed"])
    out.append("## Unanswerable probe (60 questions, last-step document masked; correct behaviour = abstain)\n")
    table(["system", "hop", "n", "abstain", "gold answer anyway", "other answer", "empty", "cites a gold doc"],
          [[s.removesuffix("_unans"), h, d["n"], *[pct(d[k]) for k in ("abstain", "gold_answer", "other", "empty", "cites_gold_doc")]]
           for s, byh in sm["unanswerable"].items() for h, d in byh.items()])
    out.append("## Entity lookup vs search, next-items in the hop traces\n")
    table(["system", "lookup share of items", "lookup: item precision", "lookup: paragraphs in gold docs", "search: item precision",
           "search: paragraphs in gold docs"],
          [[SYSTEM_LABEL[s], pct(d["lookup_item_share"]), pct(d["lookup"]["item_precision"]), pct(d["lookup"]["para_gold_precision"]),
            pct(d["search"]["item_precision"]), pct(d["search"]["para_gold_precision"])] for s, d in sm["lookup"].items()])
    out.append(f"Tokens in the committed answer files (all systems, final calls): {sum(v['all']['tokens_total'] for v in S.values())}\n")
    out.append("## Input fingerprints (sha256)\n")
    out.append("```\n" + "\n".join(f"{v}  {k}" for k, v in fp.items()) + "\n```")
    return "\n".join(out) + "\n"


def run() -> None:
    ap = argparse.ArgumentParser(prog="kb eval")
    ap.add_argument("--rerun", action="store_true", help="re-execute every LLM system first (needs LLM_* env vars)")
    a = ap.parse_args(sys.argv[2:])
    if a.rerun:
        missing = [v for v in REQUIRED_ENV if not os.environ.get(v)]
        if missing:
            sys.exit(f"--rerun needs {', '.join(missing)} (see README)")
        from kb.llm import TOKENS_PER_MIN
        tok = sum(v["all"]["tokens_total"] for v in json.loads((RESULTS / "summary.json").read_text())["systems"].values())
        print(f"expected runtime: seconds for answers already in data/cache; with an empty cache about {tok / 1e6:.0f}M tokens, "
              f">= {tok / TOKENS_PER_MIN:.0f} min at the client throttle of {TOKENS_PER_MIN // 1000}k tokens/min (provider speed decides the rest).")
        from kb import answer, verify
        sys.argv = ["kb", "answer", *LLM_SYSTEMS]
        answer.run()
        sys.argv = ["kb", "verify"]
        verify.run()
    else:
        print("expected runtime: a few seconds on a laptop (about 10 s with imports), no network, no LLM calls.")
    fp = check_inputs()
    print("inputs ok: id files match their sha256, splits disjoint, every answer file covers its question set")
    with contextlib.redirect_stdout(io.StringIO()):
        score.run()
    sm = json.loads((RESULTS / "summary.json").read_text())
    (RESULTS / "summary.md").write_text(render(sm, fp))
    print(f"wrote results/summary.json and results/summary.md\n")
    print((RESULTS / "summary.md").read_text().split("## EM by hop")[0])
